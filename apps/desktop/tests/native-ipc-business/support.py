"""Shared evidence binding and parameterized Seatbelt policy; Python standard library only."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import stat
import pwd

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
GENERATED = ('apps/desktop/src-tauri/gen/schemas/', 'apps/desktop/src-tauri/permissions/autogenerated/')


def digest(path):
    value = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            value.update(block)
    return value.hexdigest()


def no_links(path):
    path = Path(path).absolute()
    if '..' in path.parts or any(item.is_symlink() for item in (path, *path.parents)):
        raise ValueError('symlink or traversal path forbidden: ' + str(path))
    return path


def private_directory(path, create=False):
    path = no_links(path)
    if create:
        path.mkdir(mode=0o700, exist_ok=True)
    metadata = path.lstat()
    if not stat.S_ISDIR(metadata.st_mode) or metadata.st_uid != os.geteuid() or stat.S_IMODE(metadata.st_mode) != 0o700:
        raise ValueError('directory must be an owner-only real directory: ' + str(path))
    return path


def safe_file(path):
    path = no_links(path)
    metadata = path.lstat()
    if not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != os.geteuid() or metadata.st_nlink != 1 or metadata.st_mode & 0o022:
        raise ValueError('unsafe evidence file: ' + str(path))
    return path


def validate_build_paths(output, tools, cache, target):
    output, tools, cache, target = map(no_links, (output, tools, cache, target))
    if tools.name != 'bin' or tools.parent.parent.name != 'toolchains' or tools.parent.parent.parent.name != '.rustup':
        raise ValueError('toolchain must name a dedicated .rustup/toolchains/VERSION/bin')
    if target != ROOT / 'target' and not target.is_relative_to(output / 'target'):
        raise ValueError('target must be project target or below explicit output/target')
    real_home = Path(pwd.getpwuid(os.geteuid()).pw_dir)
    if cache == real_home or cache.is_relative_to(real_home) and not cache.is_relative_to(ROOT / 'output'):
        raise ValueError('cargo home must be an isolated existing cache')
    for name in ('registry', 'git'):
        path = cache / name
        if path.exists():
            resolved = path.resolve()
            if resolved != path and resolved != real_home / '.cargo' / name:
                raise ValueError('dependency link must target the exact registry/git subtree')
    return tools, cache, target


def inputs(generated=False):
    files = set()
    for name in ('Cargo.toml', 'Cargo.lock'):
        files.add(no_links(ROOT / name))
    for name in ('crates', 'apps/desktop/src-tauri', 'apps/desktop/tests/native-ipc',
                 'apps/desktop/tests/native-ipc-business', 'packaging/editions', '.cargo'):
        directory = no_links(ROOT / name)
        if directory.exists():
            for path in directory.rglob('*'):
                if {'target', 'node_modules', '__pycache__'}.intersection(path.relative_to(directory).parts):
                    continue
                no_links(path)
                if path.is_file():
                    files.add(path)
    return {str(path.relative_to(ROOT)): digest(path) for path in sorted(files)
            if path.is_file() and any(str(path.relative_to(ROOT)).startswith(prefix) for prefix in GENERATED) == generated}


def output_root(value):
    path = Path(value).absolute()
    # No resolving through links into real user data. Metadata only, never list HOME.
    for ancestor in (path, *path.parents):
        if ancestor.is_symlink():
            raise argparse.ArgumentTypeError('output ancestors must not be symlinks')
    path = path.resolve()
    home = Path(pwd.getpwuid(os.geteuid()).pw_dir)
    forbidden = [home, ROOT, *[home / name for name in ('Library', '.claude', '.claude-switcher', '.ssh', '.aws', '.config', '.cargo', '.local')]]
    if any(path == item or (item != home and item != ROOT and path.is_relative_to(item)) for item in forbidden):
        raise argparse.ArgumentTypeError('output must be a dedicated private directory')
    if path.is_relative_to(ROOT) and not path.is_relative_to(ROOT / 'output'):
        raise argparse.ArgumentTypeError('repository output must be below output/')
    path.mkdir(mode=0o700, exist_ok=True)
    metadata = path.stat()
    if stat.S_IMODE(metadata.st_mode) != 0o700 or metadata.st_uid != os.geteuid():
        raise argparse.ArgumentTypeError('output requires owner-only 0700 directory')
    return path


def make_profile(folder, output, build=False, tools=None, cache=None, target=None):
    home = Path(pwd.getpwuid(os.geteuid()).pw_dir)  # Account metadata only; no HOME content reads.
    caller_home = Path.home()
    if build:
        tools, cache, target = validate_build_paths(output, tools, cache, target)
    quote = lambda value: json.dumps(str(value))
    rules = ['(version 1)', '(allow default)', '(deny network*)',
             '(deny file-read* (subpath ' + quote(home) + '))',
             '(deny file-read* (subpath ' + quote(caller_home) + '))']
    readable = [output, HERE] + ([ROOT, tools.parent, cache] if build else [])
    if build:
        # Existing offline caches can link only these dependency subtrees elsewhere.
        readable += [(cache / name).resolve() for name in ('registry', 'git') if (cache / name).exists()]
    for path in readable:
        rules.append('(allow file-read* (subpath ' + quote(path) + '))')
    ancestors = set()
    for path in readable:
        ancestors.update(path.parents)
    rules.append('(allow file-read-metadata ' + ' '.join('(literal ' + quote(p) + ')' for p in sorted(ancestors)) + ')')
    rules += ['(deny file-write*)', '(allow file-write* (subpath ' + quote(folder) + ') (literal "/dev/null"))']
    if build:
        for path in [target, *[ROOT / name for name in GENERATED]]:
            rules.append('(allow file-write* (subpath ' + quote(path) + '))')
    for path in ['/Applications', '/Library/LaunchDaemons', '/Library/LaunchAgents', '/usr/local/bin', '/opt/homebrew/bin', ROOT / '.git']:
        rules.append('(deny file-write* (subpath ' + quote(path) + '))')
    private = [base / name for base in {home, caller_home} for name in ('Library', '.claude', '.claude.json', '.claude-switcher', '.ssh', '.aws', '.config', '.cargo/credentials', '.cargo/credentials.toml', '.cargo/config', '.cargo/config.toml', '.local/bin', 'Applications/Claude.app')]
    private += [Path(p) for p in ('/Library/Keychains', '/Library/PrivilegedHelperTools', '/Library/Application Support/claude-switcher', '/Applications/Claude.app')]
    if cache is not None:
        private += [cache / name for name in ('credentials', 'credentials.toml', 'config', 'config.toml')]
    if build:
        # Cargo takes a lock even for read-only offline dependency use.
        rules.append('(allow file-write* (literal ' + quote(cache / '.package-cache') + ') (literal ' + quote(cache / '.package-cache-mutate') + ') (literal ' + quote(cache / '.global-cache') + '))')
    for path in private:
        rules.append('(deny file-read* file-write* (subpath ' + quote(path) + '))')
    rules += ['(deny mach-lookup (regex #".*securityd.*") (regex #"(?i).*(claude|anthropic|switcher.*helper).*"))',
              '(deny process-exec (regex #".*/(security|launchctl|open|osascript|sysctl|systemsetup|networksetup|route|ifconfig|scutil|sudo|curl|defaults|pgrep|ps|killall)$") (literal "/usr/bin/true"))']
    path = folder / ('build.sb' if build else 'runtime.sb')
    with path.open('x') as stream:
        stream.write('\n'.join(rules) + '\n')
    return path
